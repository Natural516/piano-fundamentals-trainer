const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { spawnSync } = require('node:child_process')

const root = path.resolve(__dirname, '..')
const read = (relativePath) => fs.readFileSync(path.join(root, relativePath), 'utf8')

const config = read('capacitor.config.ts')
const manifest = read('android/app/src/main/AndroidManifest.xml')
const strings = read('android/app/src/main/res/values/strings.xml')
const appGradle = read('android/app/build.gradle')
const mainActivity = read('android/app/src/main/java/com/pianofundamentals/trainer/MainActivity.java')
const bluetoothMidiPlugin = read('android/app/src/main/java/com/pianofundamentals/trainer/AndroidBluetoothMidiPlugin.kt')
const updaterPlugin = read('android/app/src/main/java/com/pianofundamentals/trainer/AndroidUpdaterPlugin.kt')
const updaterPaths = read('android/app/src/main/res/xml/file_paths.xml')
const packageJson = JSON.parse(read('package.json'))
const apkPath = path.join(root, 'android/app/build/outputs/apk/debug/app-debug.apk')
assert.ok(fs.existsSync(apkPath), `debug APK missing: ${apkPath}`)
assert.ok(fs.statSync(apkPath).size > 1_000_000, 'debug APK must contain the packaged app assets')

const tempRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'piano-debug-shell-audit-'))
process.on('exit', () => fs.rmSync(tempRoot, { recursive: true, force: true }))
const jarName = process.platform === 'win32' ? 'jar.exe' : 'jar'
const jarPath = process.env.JAVA_HOME ? path.join(process.env.JAVA_HOME, 'bin', jarName) : jarName
const extraction = spawnSync(jarPath, ['xf', apkPath], {
  cwd: tempRoot,
  encoding: 'utf8',
  windowsHide: true
})
assert.equal(extraction.status, 0, `Unable to inspect Debug APK assets: ${extraction.stderr || extraction.error || 'jar failed'}`)

const publicRoot = path.join(tempRoot, 'assets/public')
const publicIndex = fs.readFileSync(path.join(publicRoot, 'index.html'), 'utf8')
const assetRoot = path.join(publicRoot, 'assets')
const assetNames = fs.readdirSync(assetRoot)
const jsBundle = assetNames
  .filter((name) => name.endsWith('.js'))
  .map((name) => fs.readFileSync(path.join(assetRoot, name), 'utf8'))
  .join('\n')

assert.match(config, /appId:\s*'com\.pianofundamentals\.trainer'/)
assert.match(config, /appName:\s*'钢琴基本功训练器'/)
assert.match(config, /webDir:\s*'dist\/android-tablet-prototype'/)
assert.doesNotMatch(config, /server\s*:\s*\{[^}]*url\s*:/s, 'native shell must not depend on a dev server URL')

assert.match(manifest, /android:screenOrientation="landscape"/)
assert.match(manifest, /android\.permission\.BLUETOOTH_SCAN/)
assert.match(manifest, /android\.permission\.BLUETOOTH_CONNECT/)
assert.match(manifest, /android\.permission\.ACCESS_FINE_LOCATION" android:maxSdkVersion="30"/)
assert.match(manifest, /android\.permission\.INTERNET/)
assert.match(manifest, /android\.permission\.REQUEST_INSTALL_PACKAGES/)
assert.match(manifest, /android:authorities="\$\{applicationId\}\.updater\.fileprovider"/)
assert.match(manifest, /android:exported="false"/)
assert.doesNotMatch(manifest, /BLUETOOTH_ADVERTISE|ACCESS_BACKGROUND_LOCATION|RECORD_AUDIO|CAMERA/)
assert.match(strings, /<string name="app_name">钢琴基本功训练器<\/string>/)
assert.match(strings, /<string name="package_name">com\.pianofundamentals\.trainer<\/string>/)
assert.match(appGradle, /applicationId "com\.pianofundamentals\.trainer"/)
assert.match(mainActivity, /extends BridgeActivity/)
assert.match(mainActivity, /registerPlugin\(AndroidBluetoothMidiPlugin\.class\)/)
assert.match(mainActivity, /registerPlugin\(AndroidUpdaterPlugin\.class\)/)
assert.match(bluetoothMidiPlugin, /03B80E5A-EDE8-4B33-A751-6CE34EC4C700/)
assert.match(bluetoothMidiPlugin, /openBluetoothDevice/)
assert.match(bluetoothMidiPlugin, /MidiDeviceInfo\.PortInfo\.TYPE_OUTPUT/)
assert.doesNotMatch(bluetoothMidiPlugin, /BluetoothGatt|markCorrect|markWrong|advanceQuestion/)
assert.match(updaterPlugin, /installVerifiedArtifact/)
assert.match(updaterPlugin, /FLAG_GRANT_READ_URI_PERMISSION/)
assert.doesNotMatch(updaterPlugin, /file:\/\/|SharedPreferences|clearApplicationUserData/)
assert.match(updaterPaths, /<cache-path name="verified_updater_artifacts" path="update\/verified\/" \/>/)
assert.doesNotMatch(updaterPaths, /external-path|files-path|external-cache-path|path="\."/)

assert.equal(packageJson.dependencies['@capacitor/core'], '8.5.0')
assert.equal(packageJson.dependencies['@capacitor/android'], '8.5.0')
assert.equal(packageJson.dependencies['@capacitor/app'], '8.1.1')
assert.match(packageJson.scripts['android:apk:debug'], /assembleDebug/)

assert.match(publicIndex, /src="\.\/assets\//)
assert.match(publicIndex, /href="\.\/assets\//)
assert.doesNotMatch(publicIndex, /https?:\/\/|localhost|127\.0\.0\.1/)
assert.ok(assetNames.some((name) => /^bravura-.*\.woff2$/i.test(name)), 'Bravura must be bundled locally')
assert.match(jsBundle, /MIDI 输入源/)
assert.match(jsBundle, /A3\.1 · DEBUG/)
assert.match(jsBundle, /DEVICE-001-APP viewport/)
assert.match(jsBundle, /backButton/)
assert.doesNotMatch(jsBundle, /openBluetoothDevice|BluetoothLeScanner|BLUETOOTH_SCAN|BLUETOOTH_CONNECT/)
process.stdout.write('PASS Capacitor identity and thin BridgeActivity shell\n')
process.stdout.write('PASS landscape lock and minimal API-level Bluetooth MIDI permissions\n')
process.stdout.write('PASS offline relative web assets and bundled Bravura font\n')
process.stdout.write('PASS Android DEBUG bundle retains explicit development MIDI and native Back handler\n')
process.stdout.write(`PASS debug APK exists: ${apkPath}\n`)
process.stdout.write('\n5/5 Android native shell checks PASS\n')
